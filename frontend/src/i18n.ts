export function t(lang: UiLang, key: string): string {
  return dict[lang]?.[key as TranslationKey] || dict.en[key as TranslationKey] || key;
}

export function formatT(lang: UiLang, key: string, values: Record<string, string>): string {
  return t(lang, key).replace(/\{(\w+)\}/g, (_, name: string) => values[name] || '');
}

export function langDir(lang: UiLang): 'ltr' | 'rtl' {
  return uiLanguages.find((item) => item.code === lang)?.dir || 'ltr';
}
